"""Convert a WorldBuilder .Civ5Map (terrain block) into a Lua data table usable from a map script.

Per-plot fields are stored as one base64-alphabet character per plot, one string per map row
(row 1 = y 0 = southern edge), so the Lua side can decode with string.byte.
River byte layout (verified geometrically against the METSL maps, see rivertest.py / flowtest.py):
  bit0 = river on E edge  (plot:SetWOfRiver)   flow: bit3 set -> SOUTH,     else NORTH
  bit1 = river on SE edge (plot:SetNWOfRiver)  flow: bit4 set -> NORTHEAST, else SOUTHWEST
  bit2 = river on SW edge (plot:SetNEOfRiver)  flow: bit5 set -> NORTHWEST, else SOUTHEAST
"""
import sys
from civ5map import read_map

ALPHA = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'


def lua_str_list(items):
    return '{' + ', '.join('"%s"' % s for s in items) + '}'


def convert(path, key):
    m = read_map(path)
    W, H = m['w'], m['h']
    plots = m['plots']

    def field(fn):
        rows = []
        for y in range(H):
            rows.append(''.join(ALPHA[fn(plots[y * W + x])] for x in range(W)))
        return rows

    # feature: 0 = none, n = features[n-1]
    feat = lambda p: 0 if p[2] == 255 else p[2] + 1
    wonder = lambda p: 0 if p[6] == 255 else p[6] + 1
    res = lambda p: 0 if p[1] == 255 else p[1] + 1
    for p in plots:
        assert p[0] < len(m['terrains']) and p[4] <= 2 and p[3] < 64 and p[5] < 64
        assert p[2] == 255 or p[2] < 63

    out = []
    out.append('-- Generated by tools/map2lua.py from %s -- do not edit by hand' % path.split('/')[-1])
    out.append('METSL_MapData = METSL_MapData or {}')
    out.append('METSL_MapData["%s"] = {' % key)
    out.append('\tW = %d, H = %d, WrapX = %s,' % (W, H, 'true' if m['settings'] & 1 else 'false'))
    out.append('\tTerrains = %s,' % lua_str_list(m['terrains']))
    out.append('\tFeatures = %s,' % lua_str_list(m['features']))
    out.append('\tWonders = %s,' % lua_str_list(m['wonders']))
    out.append('\tResources = %s,' % lua_str_list(m['resources']))
    for name, fn in [('terrain', lambda p: p[0]), ('elevation', lambda p: p[4]), ('feature', feat),
                     ('river', lambda p: p[3]), ('continent', lambda p: p[5])]:
        out.append('\t%s = {' % name)
        for r in field(fn):
            out.append('\t\t"%s",' % r)
        out.append('\t},')
    # wonders / resources are empty in the METSL maps, but keep them if present
    if any(p[6] != 255 for p in plots):
        out.append('\twonder = {')
        for r in field(wonder):
            out.append('\t\t"%s",' % r)
        out.append('\t},')
    if any(p[1] != 255 for p in plots):
        out.append('\tresource = {')
        for r in field(res):
            out.append('\t\t"%s",' % r)
        out.append('\t},')
    out.append('}')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    src, key, dst = sys.argv[1:4]
    open(dst, 'w', newline='\r\n').write(convert(src, key))
