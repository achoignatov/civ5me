# ============================================================================ art definitions
class ArtDB:
    """The landmark art defines, exactly as the pack ships them (generated by landmarks.py)."""

    def __init__(self):
        self.wonders = {}
        for w in ET.fromstring(landmarks.wonder_defines()).iter('WonderArtInfo'):
            st = w.find('WonderArtState')
            self.wonders[w.findtext('Type')] = (st.findtext('Granny'), float(st.findtext('fScale')))
        self.effects = {}
        for e in ET.fromstring(landmarks.vis_effects()).iter('VisEffectArtInfo'):
            tr = e.find('Transform')
            self.effects[e.findtext('Name')] = dict(
                translation=[float(tr.find('Translation').get(k)) for k in 'xyz'],
                rotation=[float(tr.find('Rotation').get(k)) for k in 'xyz'],
                scale=float(tr.findtext('Scale')),
                particles=[p.findtext('Name') for p in e.iter('ParticleEffect') if p.findtext('Name')],
                models=[p.findtext('Name') for p in e.iter('ModelEffect') if p.findtext('Name')])
        self.models = {m.findtext('Name'): (m.findtext('File'), float(m.findtext('fScale')))
                       for m in ET.fromstring(landmarks.vis_effect_models()).iter('VisEffectModelArtInfo')}


def asset_path(name):
    p = os.path.join(landmarks.OUT, os.path.basename(name.replace('\\', '/')))
    return p if os.path.exists(p) else None


def read_fxsxml(name):
    p = asset_path(name)
    assert p, 'missing asset %s' % name
    x = ET.parse(p).getroot()
    anim = [a.get('file') for a in x.iter('Animation') if a.get('ec') == '1000']
    tt = x.find('TimedTrigger')
    return dict(mesh=x.find('Mesh').get('file'), anim=anim[0] if anim else None,
                triggers=tt.get('file') if tt is not None else None,
                trigger_model=tt.get('model') if tt is not None else None)


def read_triggers(name):
    x = ET.parse(asset_path(name)).getroot()
    return [(t.get('bone'), t.get('event')) for t in x.iter('trigger')]


# ============================================================================ granny: models, animation, skinning
def gmat(rows16):
    """Granny 4x4 (row-major, row vectors, translation in the last row) -> mathutils Matrix."""
    return Matrix([rows16[0:4], rows16[4:8], rows16[8:12], rows16[12:16]]).transposed()


def local_matrix(pos, quat):
    x, y, z, w = quat
    return Matrix.Translation(Vector(pos)) @ Quaternion((w, x, y, z)).to_matrix().to_4x4()


def curve_value(curve, t, kind):
    v = curve['CurveData']
    name, val = v.members[0].name, v.value
    if name.endswith('DaIdentity'):
        return (0.0, 0.0, 0.0) if kind == 'pos' else (0.0, 0.0, 0.0, 1.0)
    if name.endswith('D3Constant32f') or name.endswith('D4Constant32f'):
        return tuple(val['Controls'])
    if name.endswith('D4nK16uC15u'):
        return granim.sample_quat_curve(val, t)
    raise NotImplementedError('curve format %s (add it to render_gif.curve_value)' % name)


class Animation:
    def __init__(self, path):
        r = gr2.read(path).root()
        self.duration = float(r['Animations'][0]['Duration'])
        self.groups = {tg['Name']: {t['Name']: t for t in tg['TransformTracks']} for tg in r['TrackGroups']}

    def local(self, model, bone, t):
        tr = self.groups.get(model, {}).get(bone)
        if tr is None:
            return None
        t = t % self.duration if self.duration > 0 else 0.0
        return local_matrix(curve_value(tr['PositionCurve'], t, 'pos'), curve_value(tr['OrientationCurve'], t, 'rot'))


class Model:
    """One granny model: skeleton, meshes (arrays), materials."""

    def __init__(self, root, m):
        self.name = m['Name']
        sk = m['Skeleton']
        self.bones = [(b['Name'], b['ParentIndex'],
                       local_matrix(b['Transform']['Position'], b['Transform']['Orientation']),
                       gmat(b['InverseWorldTransform'])) for b in sk['Bones']]
        self.meshes = []
        for mb in m['MeshBindings']:
            me = mb['Mesh']
            mat = me['MaterialBindings'][0]['Material']
            ext = mat['ExtendedData'].value if mat['ExtendedData'] is not None else {}
            shader = ext.get('ShaderSet') or ''
            tex = None
            for mp in mat['Maps']:
                if mp['Usage'] in ('Diffuse', 'BaseTextureMap0') and mp['Map']['Texture']:
                    tex = os.path.basename(mp['Map']['Texture']['FromFileName'].replace('\\', '/'))
            pos, uv, bidx = vertex_arrays(me)
            ib = me['PrimaryTopology']['Indices16']
            idx = (struct.unpack('<%dH' % (len(ib) // 2), ib) if isinstance(ib, (bytes, bytearray))
                   else [x['Int16'] for x in ib])
            names = [b['BoneName'] for b in me['BoneBindings']]
            self.meshes.append(dict(name=me['Name'], pos=pos, uv=uv, bone=[names[i] for i in bidx],
                                    tris=[tuple(idx[i:i + 3]) for i in range(0, len(idx), 3)],
                                    shader=shader, tex=tex, alpha=ext.get('AlphaMode')))

    def pose(self, anim, t):
        """World matrices (model space) of every bone at time t."""
        world = {}
        for name, parent, rest, _inv in self.bones:
            loc = anim.local(self.name, name, t) if anim else None
            loc = rest if loc is None else loc
            world[name] = (world[self.bones[parent][0]] @ loc) if parent >= 0 else loc
        return world

    def skin(self, mesh, world):
        inv = {n: i for n, _, _, i in self.bones}
        mats = {b: world[b] @ inv[b] for b in set(mesh['bone'])}
        return [tuple(mats[b] @ Vector(p)) for p, b in zip(mesh['pos'], mesh['bone'])]


def vertex_arrays(me):
    v = me['PrimaryVertexData']['Vertices']
    names = [m.name for m in v.members]
    if not isinstance(v.value, (bytes, bytearray)):
        return ([tuple(x['Position']) for x in v.value], [tuple(x['TextureCoordinates0'][:2]) for x in v.value],
                [x['BoneIndices'][0] if 'BoneIndices' in x else 0 for x in v.value])
    size = gr2.struct_size(v.members)
    offs, o = {}, 0
    for m in v.members:
        offs[m.name] = o
        o += gr2.struct_size([m])
    pos, uv, bidx = [], [], []
    for i in range(len(v.value) // size):
        b = i * size
        pos.append(struct.unpack_from('<3f', v.value, b + offs['Position']))
        uv.append(struct.unpack_from('<2f', v.value, b + offs['TextureCoordinates0']))
        bidx.append(v.value[b + offs['BoneIndices']] if 'BoneIndices' in names else 0)
    return pos, uv, bidx


class Asset:
    """A .fxsxml with its models and animation (a building, or a model effect)."""

    def __init__(self, fxsxml):
        self.fx = read_fxsxml(fxsxml)
        r = gr2.read(asset_path(self.fx['mesh'])).root()
        self.models = [Model(r, m) for m in r['Models']]
        self.anim = Animation(asset_path(self.fx['anim'])) if self.fx['anim'] else None
        self.triggers = read_triggers(self.fx['triggers']) if self.fx['triggers'] else []

    def duration(self):
        return self.anim.duration if self.anim else 0.0


# ============================================================================ blender scene
def texture_image(name):
    p = asset_path(name) if name else None
    if not p:
        return None
    try:
        img = dds.decode_dxt3(p)
    except AssertionError:
        return None
    h, w = img.shape[:2]
    im = bpy.data.images.new(name, w, h, alpha=True)
    im.pixels.foreach_set((np.flipud(img).astype(np.float32) / 255.0).ravel())
    return im


def make_material(mesh):
    m = bpy.data.materials.new(mesh['name'])
    m.use_nodes = True
    nt = m.node_tree
    out = nt.nodes['Material Output']
    bsdf = nt.nodes['Principled BSDF']
    im = texture_image(mesh['tex'])
    tn = None
    if im:
        tn = nt.nodes.new('ShaderNodeTexImage')
        tn.image = im
    if mesh['shader'].startswith('FXShader'):
        # additive: colour x alpha added on top of what is behind
        nt.nodes.remove(bsdf)
        em = nt.nodes.new('ShaderNodeEmission')
        tr = nt.nodes.new('ShaderNodeBsdfTransparent')
        add = nt.nodes.new('ShaderNodeAddShader')
        mul = nt.nodes.new('ShaderNodeMath'); mul.operation = 'MULTIPLY'; mul.inputs[1].default_value = 3.0
        if tn:
            nt.links.new(tn.outputs['Color'], em.inputs['Color'])
            nt.links.new(tn.outputs['Alpha'], mul.inputs[0])
        nt.links.new(mul.outputs[0], em.inputs['Strength'])
        nt.links.new(tr.outputs[0], add.inputs[0]); nt.links.new(em.outputs[0], add.inputs[1])
        nt.links.new(add.outputs[0], out.inputs['Surface'])
        m.surface_render_method = 'BLENDED'
    else:
        if tn:
            nt.links.new(tn.outputs['Color'], bsdf.inputs['Base Color'])
        bsdf.inputs['Roughness'].default_value = 0.85
    return m


class SceneMesh:
    def __init__(self, model, mesh, root_matrix):
        self.model, self.mesh = model, mesh
        me = bpy.data.meshes.new(mesh['name'])
        me.from_pydata(mesh['pos'], [], mesh['tris'])
        lay = me.uv_layers.new()
        for poly in me.polygons:
            for li in poly.loop_indices:
                u, v = mesh['uv'][me.loops[li].vertex_index]
                lay.data[li].uv = (u, 1.0 - v)
        me.materials.append(make_material(mesh))
        self.ob = bpy.data.objects.new(mesh['name'], me)
        bpy.context.scene.collection.objects.link(self.ob)
        self.root = root_matrix

    def update(self, world, root=None):
        if root is not None:
            self.root = root
        co = self.model.skin(self.mesh, world)
        flat = np.array(co, np.float32).ravel()
        self.ob.data.vertices.foreach_set('co', flat)
        self.ob.data.update()
        self.ob.matrix_world = self.root


class Fire:
    """Animated stand-in for a stock fire particle system: flickering emissive tongues + glow."""
    MAT = None

    def __init__(self, size, seed):
        if Fire.MAT is None:
            Fire.MAT = []
            for col in ((1.0, 0.85, 0.35), (1.0, 0.5, 0.1), (0.9, 0.2, 0.03)):
                m = bpy.data.materials.new('fire'); m.use_nodes = True
                nt = m.node_tree; nt.nodes.remove(nt.nodes['Principled BSDF'])
                em = nt.nodes.new('ShaderNodeEmission'); em.inputs['Color'].default_value = col + (1,)
                em.inputs['Strength'].default_value = 2.2
                tr = nt.nodes.new('ShaderNodeBsdfTransparent'); mix = nt.nodes.new('ShaderNodeMixShader')
                mix.inputs[0].default_value = 0.55
                nt.links.new(tr.outputs[0], mix.inputs[1]); nt.links.new(em.outputs[0], mix.inputs[2])
                nt.links.new(mix.outputs[0], nt.nodes['Material Output'].inputs['Surface'])
                m.surface_render_method = 'BLENDED'
                Fire.MAT.append(m)
        rng = np.random.default_rng(seed)
        self.size = size
        self.parts = []
        for i in range(7):
            bpy.ops.mesh.primitive_cone_add(vertices=7, radius1=1.0, radius2=0.0, depth=2.0)
            o = bpy.context.active_object
            o.data.transform(Matrix.Translation((0, 0, 1.0)))
            o.data.materials.append(Fire.MAT[i % 3])
            self.parts.append((o, rng.uniform(-0.35, 0.35, 2), rng.uniform(0, 6.28), rng.uniform(5, 9),
                               rng.uniform(0.55, 1.0) * (1.25 if i % 3 == 0 else 1.0)))

    def update(self, where, t, scale=1.0):
        s = self.size * scale
        for o, off, ph, fr, h in self.parts:
            flick = 0.75 + 0.25 * math.sin(t * fr + ph) + 0.12 * math.sin(t * fr * 2.3 + ph * 1.7)
            o.location = Vector(where) + Vector((off[0] * s * 0.5, off[1] * s * 0.5, -0.1 * s))
            o.scale = (0.28 * s * (0.8 + 0.2 * flick), 0.28 * s * (0.8 + 0.2 * flick), 0.5 * s * h * flick)
            o.rotation_euler = (0.25 * math.sin(t * 3 + ph), 0.25 * math.cos(t * 2.6 + ph), 0)


class Instance:
    """A placed asset (building or model effect) and everything its triggers spawn."""

    def __init__(self, db, fxsxml, root_matrix, depth=0):
        self.asset = Asset(fxsxml)
        self.root = root_matrix
        self.meshes = [SceneMesh(m, me, root_matrix) for m in self.asset.models for me in m.meshes
                       if 'Stencil' not in me['shader']]
        self.children, self.fires, self.notes = [], [], []
        model = next((m for m in self.asset.models if m.name == self.asset.fx['trigger_model']), None)
        for i, (bone, event) in enumerate(self.asset.triggers):
            e = db.effects.get(event)
            if e is None:
                self.notes.append('unknown effect %s' % event)
                continue
            for p in e['particles']:
                self.fires.append((model, bone, e, Fire(e['scale'] * FIRE_UNITS, i * 31 + depth)))
            for me_name in e['models']:
                f, fscale = db.models[me_name]
                self.children.append((model, bone, e, fscale, Instance(db, f, Matrix(), depth + 1)))

    def duration(self):
        return max([self.asset.duration()] + [c[4].duration() for c in self.children])

    def update(self, t, root=None):
        if root is not None:
            self.root = root
        poses = {m.name: m.pose(self.asset.anim, t) for m in self.asset.models}
        for sm in self.meshes:
            sm.update(poses[sm.model.name], self.root)
        scale = self.root.to_scale()[2]               # effects inherit the building's fScale
        for model, bone, e, fire in self.fires:
            w = self.root @ poses[model.name][bone]
            fire.update(w.translation, t, scale)
        for model, bone, e, fscale, inst in self.children:
            r = Matrix.Rotation(math.radians(e['rotation'][2]), 4, 'Z') @ \
                Matrix.Rotation(math.radians(e['rotation'][1]), 4, 'Y') @ \
                Matrix.Rotation(math.radians(e['rotation'][0]), 4, 'X')
            m = self.root @ poses[model.name][bone] @ Matrix.Translation(e['translation']) @ r @ \
                Matrix.Scale(e['scale'] * fscale, 4)
            inst.update(t, m)

    def has_particles(self):
        return bool(self.fires) or any(c[4].has_particles() for c in self.children)


def setup_scene(size, world_bounds):
    sc = bpy.context.scene
    sc.render.engine = 'BLENDER_EEVEE_NEXT'
    sc.render.resolution_x, sc.render.resolution_y = size
    sc.render.film_transparent = False
    sc.view_settings.view_transform = 'Standard'
    try:
        sc.eevee.taa_render_samples = 16
    except AttributeError:
        pass
    w = bpy.data.worlds.new('w'); w.use_nodes = True
    w.node_tree.nodes['Background'].inputs['Color'].default_value = (0.32, 0.30, 0.30, 1)
    w.node_tree.nodes['Background'].inputs['Strength'].default_value = 0.6
    sc.world = w
    sun = bpy.data.objects.new('sun', bpy.data.lights.new('sun', 'SUN'))
    sun.data.energy = 3.2
    sun.rotation_euler = (math.radians(48), math.radians(-22), math.radians(-28))
    sc.collection.objects.link(sun)
    # ground with the city hexagon and its neighbours (pointy-top, flat sides E/W)
    bpy.ops.mesh.primitive_plane_add(size=600, location=(0, 0, -0.02))
    g = bpy.context.active_object
    gm = bpy.data.materials.new('ground'); gm.use_nodes = True
    gm.node_tree.nodes['Principled BSDF'].inputs['Base Color'].default_value = (0.20, 0.18, 0.15, 1)
    g.data.materials.append(gm)
    hin = landmarks.ENVELOPE['hex_in']
    hout = landmarks.ENVELOPE['hex_out']
    lm = bpy.data.materials.new('hex'); lm.use_nodes = True
    lm.node_tree.nodes['Principled BSDF'].inputs['Base Color'].default_value = (0.75, 0.68, 0.35, 1)
    verts, faces = [], []
    for cx, cy in [(0.0, 0.0)] + [(2 * hin * math.cos(math.radians(60 * k)), 2 * hin * math.sin(math.radians(60 * k)))
                                  for k in range(6)]:
        cs = [(cx + hout * math.cos(math.radians(30 + 60 * k)), cy + hout * math.sin(math.radians(30 + 60 * k)))
              for k in range(7)]
        for (x0, y0), (x1, y1) in zip(cs, cs[1:]):
            dx, dy = x1 - x0, y1 - y0
            L = math.hypot(dx, dy); nx, ny = -dy / L * 0.2, dx / L * 0.2
            n0 = len(verts)
            verts += [(x0 - nx, y0 - ny, 0), (x1 - nx, y1 - ny, 0), (x1 + nx, y1 + ny, 0), (x0 + nx, y0 + ny, 0)]
            faces.append((n0, n0 + 1, n0 + 2, n0 + 3))
    me = bpy.data.meshes.new('hexlines'); me.from_pydata(verts, [], faces); me.materials.append(lm)
    sc.collection.objects.link(bpy.data.objects.new('hexlines', me))
    cam = bpy.data.objects.new('cam', bpy.data.cameras.new('cam'))
    sc.collection.objects.link(cam)
    sc.camera = cam
    return cam


def aim(cam, loc, target, lens):
    cam.location = Vector(loc)
    cam.data.lens = lens
    cam.rotation_euler = (Vector(target) - cam.location).to_track_quat('-Z', 'Y').to_euler()


VIEWS = {
    # the game's strategic camera: from the south, looking down ~50 degrees, a couple of tiles in view
    'game': lambda top: ((0, -120, 110), (0, -14, 22), 31),
    # close-up on the top of the landmark (the Eye)
    # from the left: the Eye mostly looks right, so the beam sweeps away from this camera
    'close': lambda top: ((-30, -22, top + 14), (0, -1, top - 7), 40),
}


def render(tag, db, views, fps, size, seconds):
    fxsxml, fscale = db.wonders[tag]
    bpy.ops.wm.read_factory_settings(use_empty=True)
    Fire.MAT = None
    cam = setup_scene(size, None)
    inst = Instance(db, fxsxml, Matrix.Scale(fscale, 4))
    T = seconds or inst.duration() or 1.0
    n = max(1, int(round(T * fps)))
    tops = [max(p[2] for p in me['pos']) * fscale for m in inst.asset.models for me in m.meshes
            if 'Stencil' not in me['shader']]
    top = max(tops)
    from PIL import Image, ImageDraw, ImageFont
    os.makedirs(os.path.join(GIF_DIR, 'frames'), exist_ok=True)
    caption = '%s   %s' % (tag, 'fire = stand-in for the game\'s particles' if inst.has_particles() else '')
    outs = []
    for view in views:
        loc, target, lens = VIEWS[view](top)
        aim(cam, loc, target, lens)
        frames = []
        for i in range(n):
            t = T * i / n
            inst.update(t)
            p = os.path.join(GIF_DIR, 'frames', '%s_%s_%03d.png' % (tag, view, i))
            bpy.context.scene.render.filepath = p
            bpy.ops.render.render(write_still=True)
            im = Image.open(p).convert('RGB')
            d = ImageDraw.Draw(im)
            try:
                font = ImageFont.load_default(size=14)
            except TypeError:
                font = ImageFont.load_default()
            d.rectangle((0, size[1] - 22, size[0], size[1]), fill=(0, 0, 0))
            d.text((6, size[1] - 19), '%s   t=%4.1fs / %.1fs' % (caption, t, T), fill=(235, 220, 180), font=font)
            frames.append(im)
        gif = os.path.join(GIF_DIR, '%s_%s.gif' % (tag, view))
        pal = [f.quantize(colors=255, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE) for f in frames]
        pal[0].save(gif, save_all=True, append_images=pal[1:], duration=int(round(1000.0 / fps)), loop=0,
                    optimize=True, disposal=1)
        outs.append(gif)
        print('GIF %s  (%d frames, %.1f s loop, %d KB)%s' % (gif, n, T, os.path.getsize(gif) // 1024,
                                                              ('  notes: ' + '; '.join(inst.notes)) if inst.notes else ''))
    return outs


def main():
    argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []

    def opt(name, default):
        return argv[argv.index(name) + 1] if name in argv else default
    view = opt('--view', 'both')
    views = ['game', 'close'] if view == 'both' else [view]
    fps = float(opt('--fps', 12))
    size = tuple(int(x) for x in opt('--size', '640x480').split('x'))
    seconds = float(opt('--seconds', 0)) or None
    skip = {opt(k, None) for k in ('--view', '--fps', '--size', '--seconds')}
    names = [a for a in argv if not a.startswith('--') and a not in skip]
    db = ArtDB()
    tags = []
    for lm in landmarks.LANDMARKS:
        if not names or lm['model'] in names or lm['module'] in names or landmarks.art_tag(lm) in names:
            tags.append(landmarks.art_tag(lm))
    tags += [t for t in names if t in db.wonders and t not in tags]
    for tag in tags:
        render(tag, db, views, fps, size, seconds)


if __name__ == '__main__':
    main()
