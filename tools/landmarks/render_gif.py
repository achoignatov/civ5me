"""Render a landmark's model, animation and effects to a looping GIF, FROM THE WRITTEN GAME FILES.

Run:  blender -b --factory-startup -P tools/landmarks/render_gif.py -- [landmark ...] [options]
        landmark      model or module name (default: every landmark); diagnostic variants by art tag, e.g. MEC_LM_BARAD_DUR_T2
        --view V      game | close | both          (default both)
        --fps N       frames per second            (default 12)
        --size WxH    pixels                        (default 640x480)
        --seconds S   length (default: the longest animation in the asset, i.e. one full loop)
Output: build/landmarks/gif/<tag>_<view>.gif   (+ the frames in build/landmarks/gif/frames/)

It works like the engine, not like the Blender scene the model came from, so it catches mistakes in
the shipped files:
  WonderArtInfo (tag -> .fxsxml, fScale) -> .fxsxml (Mesh, Animation ec=1000, TimedTrigger, Textures)
  -> .gr2 models: every TrackGroup/track of the animation evaluated at time t with the stored curves
     (DaIdentity, D3Constant32f, D4Constant32f, D4nK16uC15u; granim), bone world matrices from the
     parent chain, vertices skinned with the file's own InverseWorldTransforms (BoneIndices/weights);
  -> trigger file -> (bone, event) -> VisEffect (Transform, ParticleEffects, ModelEffects) ->
     model effects: their own .fxsxml / .gr2 / animation, recursively, attached to the bone;
     particle effects: an animated fire STAND-IN (the particle files are the game's own format),
     marked in the caption;
  everything below the building is scaled by its fScale, effects included (like the stock ones).
Materials: BuildingShader -> lit texture; FXShader (additive) -> emission x alpha, added; stencils hidden.
"""
